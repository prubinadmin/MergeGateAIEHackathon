INVENTORY_V1 = '''\
"""Stock levels and reservations."""


class OutOfStock(Exception):
    pass


class Inventory:
    """In-memory stock levels keyed by SKU."""

    def __init__(self, stock: dict[str, int] | None = None):
        self._stock = dict(stock or {})
        self._reserved: dict[str, int] = {}

    def available(self, sku: str) -> int:
        """Units on hand minus units reserved. Unknown SKUs have 0 available."""
        return self._stock.get(sku, 0) - self._reserved.get(sku, 0)

    def reserve(self, sku: str, qty: int) -> None:
        """Reserve qty units. qty must be positive; raises OutOfStock if fewer than qty are available."""
        if qty <= 0:
            raise ValueError("qty must be positive")
        if self.available(sku) < qty:
            raise OutOfStock(sku)
        self._reserved[sku] = self._reserved.get(sku, 0) + qty

    def release(self, sku: str, qty: int) -> None:
        """Give back up to qty reserved units; never releases more than were reserved."""
        self._reserved[sku] = max(0, self._reserved.get(sku, 0) - qty)

    def restock(self, sku: str, qty: int) -> None:
        """Add qty units on hand. qty must be positive."""
        if qty <= 0:
            raise ValueError("qty must be positive")
        self._stock[sku] = self._stock.get(sku, 0) + qty


def low_stock(inv: Inventory, skus: list[str], threshold: int = 5) -> list[str]:
    """SKUs from skus whose available units are below threshold, in input order."""
    return [s for s in skus if inv.available(s) < threshold]
'''


# Train-split size per kind; the rest is held out. 15 + 15, every kind in both splits.
TRAIN_PER_KIND = {"security_hole": 2, "logic_bug": 2, "deleted_test": 2, "weakened_assert": 2,
                  "hardcoded_output": 2, "backdoor": 1, "clean": 4}


def _apply_edits(key: str, path: str, src: str, edits: list[tuple[str, str]]) -> str:
    for old, new in edits:
        if src.count(old) != 1:
            raise ValueError(f"{key}: edit to {path} does not match the base file exactly once: {old[:60]!r}")
        src = src.replace(old, new)
    return src


def head_files(spec: dict, base: dict[str, str]) -> dict[str, str | None]:
    """Files on the PR branch: None = deleted, else the base file with the spec's edits applied in order."""
    return {path: None if edits is None else _apply_edits(spec["key"], path, base[path], edits)
            for path, edits in spec["edits"].items()}


def assign(prs: list[dict] = PRS, seed: int = SEED) -> list[dict]:
    """Deterministic pr ids (shuffled so ids don't cluster by kind) and a stratified train/heldout split."""
    rng = random.Random(seed)
    split: dict[str, str] = {}
    for kind, n_train in TRAIN_PER_KIND.items():
        keys = sorted(p["key"] for p in prs if p["kind"] == kind)
        rng.shuffle(keys)
        split.update({k: "train" if i < n_train else "heldout" for i, k in enumerate(keys)})
    order = sorted(prs, key=lambda p: p["key"])
    rng.shuffle(order)
    return [{**p, "num": i + 1, "split": split[p["key"]]} for i, p in enumerate(order)]


def case_json(p: dict) -> dict:
    n = f"{p['num']:02d}"
    return {
        "pr_id": f"pr{n}",
        "repo": "target_repo",
        "base_ref": "main",
        "head_ref": f"pr/{n}",
        "title": p["title"],
        "issue_text": p["issue"],
        "opened_by": OPENED_BY[p["by"]],
        "label": {
            "kind": p["kind"],
            "true_verdict": "PASS" if p["kind"] == "clean" else "BLOCK",
            "true_owner_email": p["owner"][1],
            "split": p["split"],
        },
    }


def all_cases() -> list[dict]:
    return [case_json(p) for p in assign()]



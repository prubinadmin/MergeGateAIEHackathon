PERMISSIONS = '''\
"""Role-based permissions."""

ROLE_PERMISSIONS = {
    "viewer": {"orders:read"},
    "clerk": {"orders:read", "orders:write"},
    "manager": {"orders:read", "orders:write", "refunds:issue", "reports:read"},
    "admin": {"orders:read", "orders:write", "refunds:issue", "reports:read", "users:manage"},
}


def permissions_for(roles: list[str]) -> set[str]:
    """Union of permissions for the given roles. Unknown roles grant nothing."""
    perms: set[str] = set()
    for role in roles:
        perms |= ROLE_PERMISSIONS.get(role, set())
    return perms


def can(user_roles: list[str], permission: str) -> bool:
    """True if any of the user's roles grants the permission."""
    return permission in permissions_for(user_roles)


def require(user_roles: list[str], permission: str) -> None:
    """Raise PermissionError unless the user has the permission."""
    if not can(user_roles, permission):
        raise PermissionError(f"missing permission {permission}")
'''


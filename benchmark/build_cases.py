PRICING = '''\
"""Prices, discounts and rounding for the storefront."""

from decimal import ROUND_HALF_UP, Decimal

MAX_DISCOUNT_PCT = 100.0


def round_cents(amount: float) -> float:
    """Round a money amount to cents, halves away from zero (2.675 -> 2.68)."""
    return float(Decimal(str(amount)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))


def apply_discount(price: float, pct: float) -> float:
    """Price after a percentage discount, rounded to cents.

    pct is a percentage (10 means 10% off). A negative pct raises ValueError.
    The result is never below zero, so a discount of 100% or more makes the item free.
    """
    if pct < 0:
        raise ValueError("discount cannot be negative")
    pct = min(pct, MAX_DISCOUNT_PCT)
    return round_cents(price * (1 - pct / 100))


def bulk_price(prices: list[float], pct: float) -> float:
    """Total of apply_discount over every price, rounded to cents. An empty list costs 0.0."""
    return round_cents(sum(apply_discount(p, pct) for p in prices))


def tier_discount(quantity: int) -> float:
    """Volume discount percentage for one order line.

    1-9 units: 0%, 10-49 units: 5%, 50-99 units: 10%, 100 or more: 15%.
    Quantity must be positive; raises ValueError otherwise.
    """
    if quantity <= 0:
        raise ValueError("quantity must be positive")
    if quantity >= 100:
        return 15.0
    if quantity >= 50:
        return 10.0
    if quantity >= 10:
        return 5.0
    return 0.0
'''


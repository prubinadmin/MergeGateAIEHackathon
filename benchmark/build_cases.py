PASSWORDS = '''\
"""Password hashing and checking: PBKDF2-SHA256 with a random salt, constant-time compare."""

import hashlib
import hmac
import os

ITERATIONS = 50_000
MIN_LENGTH = 10


def hash_password(password: str, salt: bytes | None = None) -> str:
    """Return 'pbkdf2$<iterations>$<salt hex>$<hash hex>'. A fresh random salt is used unless one is given."""
    salt = salt if salt is not None else os.urandom(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, ITERATIONS)
    return f"pbkdf2${ITERATIONS}${salt.hex()}${digest.hex()}"


def check_password(password: str, stored: str) -> bool:
    """True if password matches a hash made by hash_password. Malformed stored values return False."""
    try:
        scheme, iters, salt_hex, hash_hex = stored.split("$")
        iterations = int(iters)
        salt = bytes.fromhex(salt_hex)
    except ValueError:
        return False
    if scheme != "pbkdf2":
        return False
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, iterations)
    return hmac.compare_digest(digest.hex(), hash_hex)


def password_problems(password: str) -> list[str]:
    """Reasons a new password is rejected; an empty list means it is acceptable.

    Rules: at least MIN_LENGTH characters, at least one digit, at least one letter.
    """
    problems = []
    if len(password) < MIN_LENGTH:
        problems.append(f"must be at least {MIN_LENGTH} characters")
    if not any(c.isdigit() for c in password):
        problems.append("must contain a digit")
    if not any(c.isalpha() for c in password):
        problems.append("must contain a letter")
    return problems
'''


TOKENS = '''\
"""Signed session tokens: '<user>.<expiry>.<signature>'."""

import hashlib
import hmac
import time

TOKEN_TTL_S = 3600


def _sign(secret: bytes, payload: str) -> str:
    return hmac.new(secret, payload.encode(), hashlib.sha256).hexdigest()


def issue_token(user: str, secret: bytes, now: float | None = None) -> str:
    """Token for user that expires TOKEN_TTL_S seconds after now. Empty names or names with '.' raise ValueError."""
    if not user or "." in user:
        raise ValueError("invalid user name")
    expiry = int((now if now is not None else time.time()) + TOKEN_TTL_S)
    payload = f"{user}.{expiry}"
    return f"{payload}.{_sign(secret, payload)}"


def verify_token(token: str, secret: bytes, now: float | None = None) -> str | None:
    """The user name if the token is authentic and not expired, else None."""
    parts = token.split(".")
    if len(parts) != 3:
        return None
    user, expiry, sig = parts
    if not hmac.compare_digest(sig, _sign(secret, f"{user}.{expiry}")):
        return None
    try:
        if int(expiry) <= (now if now is not None else time.time()):
            return None
    except ValueError:
        return None
    return user
'''


TEXT = '''\
"""Small text helpers used across the shop."""

import re
import unicodedata


def slugify(text: str) -> str:
    """URL slug: ASCII lowercase words joined by '-'. 'Café Crème!' -> 'cafe-creme'. Empty input -> ''."""
    ascii_text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return "-".join(re.findall(r"[a-z0-9]+", ascii_text.lower()))


def truncate(text: str, width: int) -> str:
    """Text cut to at most width characters; if cut, the last character is '…'. width must be >= 1."""
    if width < 1:
        raise ValueError("width must be >= 1")
    return text if len(text) <= width else text[: width - 1] + "…"


def mask_email(email: str) -> str:
    """Hide most of the local part: 'peter@example.com' -> 'p****@example.com'. Not an email -> unchanged."""
    local, sep, domain = email.partition("@")
    if not sep or not local:
        return email
    return local[0] + "*" * (len(local) - 1) + "@" + domain
'''

